#!/bin/bash

# ==================================================
# 1. 一時設定（現在のターミナルセッションにのみ適用されます）
# ==================================================
export MY_VAR="value"

echo $MY_VAR

# ==================================================
# 2. 恒久設定（ユーザー個別の環境に常に適用されます）
# ==================================================

# ~/.bashrc ファイルの末尾に設定構文を直接追加します
echo 'export MY_VAR="hello"' >> ~/.bashrc

# 変更された設定を即座に反映します
source ~/.bashrc

# 恒久適用されたか確認します
echo $MY_VAR

# ==================================================
# ■ ~/.bashrc について
# ~/.bashrc は、Bashターミナルが起動するたびに自動的に実行される個人設定ファイルです。
#
# ~      : ユーザーのホームディレクトリを表します。
# .      : 名前の先頭にある点は隠しファイルを意味します。
# bashrc : Bash Run Commands（Bash起動時に実行するコマンド群）の略です。
#
# ■ 主な役割
# ・環境変数の自動適用: ターミナルを再起動しても維持されるよう、export 構文を保存します。
# ・コマンド短縮キー（エイリアス）の登録: 長く複雑なコマンドを短い単語に短縮できます。（例: alias ll='ls -la'）
# ・ターミナルのカスタマイズ: プロンプトの文字色やデザインを変更できます。
#
# ==================================================
# ■ GUIでの設定方法（Windows）
# 1. Win + R キーを押して「ファイル名を指定して実行」ウィンドウを開き、sysdm.cpl と入力してEnterを押します。（システムのプロパティ画面が開きます）
# 2. [詳細設定] タブ → 下部の [環境変数(N)...] をクリックします。
# 3. [ユーザー環境変数] または [システム環境変数] の下にある [新規(N)...] をクリックします。
# 4. 変数名と変数値（値）を入力し、[OK] を押して保存します。